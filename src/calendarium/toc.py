"""Table-of-contents (TOC) loading of country configurations.

Instead of one package per country (as the original .NET project did with
NuGet), countries can be loaded on demand from any location described by a
small TOC file.  A TOC is a text file with one entry per line::

    # country;culture;uri
    France;fr-FR;date_France.json
    Germany;de-DE;date_Germany.json

The ``uri`` may be absolute (``https://...``, ``file://...``) or relative,
in which case it is resolved **against the location of the TOC itself** --
so the same TOC file works served over HTTP, from a local clone, or from
any mirror.

The TOC of this repository is published at
``src/calendarium/data/countries/toc.txt`` (see :data:`DEFAULT_TOC_URL`
for the raw GitHub address) and is regenerated by
``scripts/update_toc.py``.

Usage::

    from calendarium import Calendarium, Toc

    # everything the TOC lists
    cal = Calendarium.from_toc("https://raw.githubusercontent.com/.../toc.txt")

    # or pick countries by name or culture code
    cal = Calendarium.from_toc("path/to/toc.txt", countries=["fr-FR", "Germany"])

    # or inspect the TOC first
    toc = Toc.load("path/to/toc.txt")
    print(toc.countries())
    configuration = toc.load_country("fr-FR")
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, List, Optional, Union
from urllib.parse import urljoin, urlparse
from urllib.request import url2pathname, urlopen

from .loader import loads
from .models import CountryConfiguration

#: Raw address of the TOC published in this repository (main branch).
#: Its URIs are relative and resolve against the TOC location.
DEFAULT_TOC_URL = (
    "https://raw.githubusercontent.com/gaelgael5/calendarium/"
    "main/src/calendarium/data/countries/toc.txt"
)

#: Same TOC with absolute URLs: copy or mirror it anywhere, its entries
#: keep pointing at this repository.
DEFAULT_TOC_FULL_URL = (
    "https://raw.githubusercontent.com/gaelgael5/calendarium/"
    "main/src/calendarium/data/countries/toc.full.txt"
)


def _fetch(source: Union[str, Path], timeout: float) -> tuple[str, Union[str, Path]]:
    """Return ``(text, base)`` where ``base`` resolves relative URIs."""
    text_source = str(source)
    parsed = urlparse(text_source)

    if parsed.scheme in ("http", "https"):
        with urlopen(text_source, timeout=timeout) as response:  # nosec B310
            return response.read().decode("utf-8-sig"), text_source

    if parsed.scheme == "file":
        path = Path(url2pathname(parsed.path))
        return path.read_text(encoding="utf-8-sig"), path

    path = Path(source)
    return path.read_text(encoding="utf-8-sig"), path


def _resolve(base: Union[str, Path], uri: str) -> str:
    """Resolve ``uri`` against the TOC location ``base``."""
    parsed = urlparse(uri)
    if parsed.scheme in ("http", "https", "file"):
        return uri
    if isinstance(base, str):  # the TOC came from an http(s) URL
        return urljoin(base, uri)
    return str((base.parent / uri).resolve())


@dataclass(frozen=True)
class TocEntry:
    """One TOC line: a country, its culture code and its resolved URI."""

    country: str
    culture: str
    uri: str


class Toc:
    """A parsed table of contents of country configurations."""

    def __init__(self, entries: List[TocEntry], source: str):
        self.entries = entries
        self.source = source

    # -- loading -----------------------------------------------------------

    @classmethod
    def load(cls, source: Union[str, Path], timeout: float = 10.0) -> "Toc":
        """Load a TOC from an ``http(s)://`` URL, a ``file://`` URI or a
        local path."""
        text, base = _fetch(source, timeout)
        return cls.parse(text, base, source=str(source))

    @classmethod
    def parse(cls, text: str, base: Union[str, Path], source: str = "<text>") -> "Toc":
        entries = []
        for line_number, raw in enumerate(text.splitlines(), start=1):
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            parts = [part.strip() for part in line.split(";")]
            if len(parts) != 3 or not parts[0] or not parts[2]:
                raise ValueError(
                    f"{source}:{line_number}: expected 'country;culture;uri', got {raw!r}"
                )
            country, culture, uri = parts
            entries.append(TocEntry(country, culture, _resolve(base, uri)))
        return cls(entries, source=source)

    # -- queries -----------------------------------------------------------

    def countries(self) -> List[str]:
        return [entry.country for entry in self.entries]

    def find(self, key: str) -> Optional[TocEntry]:
        """Entry whose country name or culture code matches ``key``
        (case-insensitive).  Country names win over cultures; an ambiguous
        culture raises ``ValueError``."""
        lowered = key.strip().lower()
        for entry in self.entries:
            if entry.country.lower() == lowered:
                return entry
        matches = [entry for entry in self.entries if entry.culture.lower() == lowered]
        if len(matches) > 1:
            names = ", ".join(entry.country for entry in matches)
            raise ValueError(f"culture {key!r} is ambiguous in this TOC: {names}")
        return matches[0] if matches else None

    # -- configuration loading ----------------------------------------------

    def load_country(self, key: str, timeout: float = 10.0) -> CountryConfiguration:
        """Fetch and parse the configuration of one country (by name or
        culture code)."""
        entry = self.find(key)
        if entry is None:
            raise KeyError(
                f"{key!r} not found in TOC {self.source} "
                f"(countries: {', '.join(self.countries())})"
            )
        text, _ = _fetch(entry.uri, timeout)
        return loads(text, source_file=entry.uri)

    def load_all(
        self,
        countries: Optional[Iterable[str]] = None,
        timeout: float = 10.0,
    ) -> List[CountryConfiguration]:
        """Fetch every listed configuration, or only the given countries
        (names or culture codes)."""
        if countries is None:
            keys = self.countries()
        else:
            keys = list(countries)
        return [self.load_country(key, timeout) for key in keys]


def load_toc(source: Union[str, Path] = DEFAULT_TOC_URL, timeout: float = 10.0) -> Toc:
    """Shortcut for :meth:`Toc.load` (defaults to this repository's TOC)."""
    return Toc.load(source, timeout)
